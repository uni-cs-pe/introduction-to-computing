#include <stdio.h>

// Una comparación es una expresión: vale 1 si es cierta y 0 si es falsa.
int main(void) {
    int a = 5;
    int b = 3;

    printf("a > b  vale %d\n", a > b);
    printf("a < b  vale %d\n", a < b);
    printf("a == b vale %d\n", a == b);
    printf("a != b vale %d\n", a != b);
    printf("a >= 5 vale %d\n", a >= 5);
    printf("a <= 4 vale %d\n", a <= 4);

    return 0;
}
